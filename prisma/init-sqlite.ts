function canIgnoreSqliteInitError(error: unknown) {
  if (!(error instanceof Error)) return false;
  return error.message.includes("duplicate column name") || error.message.includes("already exists");
}

async function main() {
  for (const statement of statements) {
    try {
      await prisma.$executeRawUnsafe(statement);
    } catch (error) {
      if (!canIgnoreSqliteInitError(error)) throw error;
    }
  }
  console.log("SQLite development database is ready.");
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
